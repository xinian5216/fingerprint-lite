const STRINGS: Record<Lang, Dict> = { en, 'zh-CN': zh }

/** Render a dictionary string with {name} placeholders filled in. */
export function render(key: string, lang: Lang, vars?: Record<string, string | number>): string {
  let text = STRINGS[lang][key] ?? STRINGS.en[key] ?? key
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
  }
  return text
}

const LangContext = createContext<{ lang: Lang; setLang: (lang: Lang) => void }>({
  lang: 'zh-CN',
  setLang: () => undefined,
})

function storedLang(): Lang {
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY)
    if (saved === 'en' || saved === 'zh-CN') return saved
  } catch {
    // localStorage unavailable (prerender): fall through to the default.
  }
  return 'zh-CN'
}

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>('zh-CN')

  useEffect(() => {
    // eslint-disable-next-line react-hooks/set-state-in-effect
    setLangState(storedLang())
  }, [])

  useEffect(() => {
    document.documentElement.lang = lang
    try {
      window.localStorage.setItem(STORAGE_KEY, lang)
    } catch {
      // Private mode: the UI still works, the choice just does not persist.
    }
  }, [lang])

  const setLang = useCallback((next: Lang) => setLangState(next), [])

  return <LangContext.Provider value={{ lang, setLang }}>{children}</LangContext.Provider>
}

export function useLang(): { lang: Lang; setLang: (lang: Lang) => void } {
  return useContext(LangContext)
}

/** Bound translator for the current language: t('pl.new') in render. */
export function useT(): (key: string, vars?: Record<string, string | number>) => string {
  const { lang } = useLang()
  return useCallback((key: string, vars?: Record<string, string | number>) => render(key, lang, vars), [lang])
}
